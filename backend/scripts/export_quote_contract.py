"""Generate frontend identities directly from the backend contract; --check is CI-safe."""
import argparse
import json
from pathlib import Path

from app.pricing_contract import (
    ENGINE_VERSION, WORKSPACE_VERSION, STATE_LABELS, MAX_PARAMETER_BLOCKS,
    MAX_PARAMETER_FIELDS, MAX_COSTS,
)
from app.process_taxonomy import PROCESS_LABELS
from app.requirements_schemas import PARAMETER_FIELDS
from app.pricing_proposals import Parameters


def render():
    if len(Parameters.model_fields) > MAX_PARAMETER_FIELDS:
        raise ValueError("The compiled assumption limit must cover every field in a parameter block.")
    values = {
        "workspaceVersion": WORKSPACE_VERSION, "pricingEngineVersion": ENGINE_VERSION,
        "workflowLabels": STATE_LABELS, "processLabels": PROCESS_LABELS,
        "parameterFields": {key: sorted(value) for key, value in PARAMETER_FIELDS.items()},
        "pricingLimits": {"parameterBlocks": MAX_PARAMETER_BLOCKS, "costs": MAX_COSTS,
                          "compiledAssumptions": MAX_PARAMETER_BLOCKS * MAX_PARAMETER_FIELDS},
    }
    return "// Generated by backend/scripts/export_quote_contract.py. Do not edit.\n" + "\n".join(
        f"export const {key} = {json.dumps(value, ensure_ascii=False, indent=2)} as const"
        for key, value in values.items()) + (
            "\nexport type WorkflowState = keyof typeof workflowLabels\n"
            "export type ProcessCode = keyof typeof processLabels\n")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = Path(__file__).resolve().parents[2] / "frontend/src/generated-quote-contract.ts"
    content = render()
    if args.check:
        if not target.is_file() or target.read_text(encoding="utf-8") != content:
            raise SystemExit("Frontend quotation contract is stale; regenerate it before release.")
    else:
        target.write_text(content, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
