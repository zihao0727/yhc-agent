const { chromium } = require('playwright')
const { readFileSync, mkdirSync } = require('node:fs')
const { parseEnv } = require('node:util')
const path = require('node:path')
const assert = require('node:assert/strict')

async function main() {
  const root = path.resolve(__dirname, '..')
  const config = parseEnv(readFileSync(path.join(root, 'backend/.env'), 'utf8'))
  const output = path.join(root, '.runtime/screenshots')
  mkdirSync(output, { recursive: true })
  const jobId = Number(process.env.JOB_ID || 21)
  assert(Number.isSafeInteger(jobId) && jobId > 0)
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.addInitScript(token => sessionStorage.setItem('firefly-token', token), config.ADMIN_TOKEN)
  await page.route('**/api/**', route => {
    assert.equal(route.request().method(), 'GET', 'Real order layout verification remains read-only')
    return route.continue()
  })
  async function snapshot(name) {
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${name}: page overflow`)
    await page.screenshot({ path: path.join(output, `quote-layout-${name}.png`), animations: 'disabled' })
  }
  try {
    await page.goto(process.env.UI_URL || 'http://127.0.0.1:5173')
    await page.locator('.chat-history-item').first().waitFor()
    await page.locator(`.chat-history-item[data-job-id="${jobId}"]`).click()
    await page.getByRole('tab', { name: /^待补充/ }).click()
    const group = page.locator('.supplement-row').filter({ hasText: '建筑入口标识（演员）' }).first()
    await group.locator('.supplement-heading').click()
    const projects = group.locator('.supplement-project')
    assert(await projects.count() >= 2, 'Each grouped project has its own form')
    assert.equal(await group.locator('.supplement-other-fields').getAttribute('open'), null)
    assert.equal(await group.locator('.supplement-technical').isVisible(), false)
    assert.equal(await group.locator('.supplement-question').count(), 0, 'No duplicate paragraph before scoped forms')
    const firstGrid = group.locator('.supplement-object-field-grid').first()
    assert.equal(await firstGrid.evaluate(element => getComputedStyle(element).gridTemplateColumns.split(' ').length), 3)
    await snapshot('supplement-desktop')
    const second = projects.nth(1)
    await second.scrollIntoViewIfNeeded()
    await snapshot('supplement-fields-desktop')
    await page.setViewportSize({ width: 390, height: 844 })
    await second.locator('.supplement-project-header').scrollIntoViewIfNeeded()
    assert.equal(await firstGrid.evaluate(element => getComputedStyle(element).gridTemplateColumns.split(' ').length), 1)
    await snapshot('supplement-mobile')
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.getByRole('tab', { name: '报价结果', exact: true }).click()
    const row = page.locator('.result-table tbody tr').filter({ hasText: '建筑入口标识（办公）' }).first()
    await row.getByRole('button', { name: '建筑入口标识（办公）', exact: true }).click()
    const drawer = page.getByRole('dialog', { name: '建筑入口标识（办公）', exact: true })
    const issues = drawer.locator('.result-needed')
    assert.match(await issues.innerText(), /LED电源.*单价/s)
    assert.doesNotMatch(await issues.innerText(), /catalog_id|billable_area_m2|连续操作|尚未选择价格/)
    assert.equal(await drawer.locator('.result-pricing-notes').getAttribute('open'), null)
    assert.equal(await drawer.locator('.result-pricing-notes ul').isVisible(), false)
    assert.equal(await drawer.locator('.result-facts').first().isVisible(), false, 'No duplicate empty price row')
    for (const [name, width, height] of [['desktop', 1440, 1000], ['tablet', 768, 1024], ['mobile', 390, 844], ['narrow', 320, 740]]) {
      await page.setViewportSize({ width, height })
      await snapshot(`detail-${name}`)
      assert(await drawer.evaluate(element => element.scrollWidth <= element.clientWidth), `${name}: drawer overflow`)
    }
    await drawer.locator('.result-pricing-notes > summary').click()
    assert.match(await drawer.locator('.result-pricing-notes ul').innerText(), /现场安装|工艺难度/)
    await page.setViewportSize({ width: 1440, height: 1000 })
    await drawer.locator('.el-drawer__close-btn').click()
    await drawer.waitFor({ state: 'hidden' })
    await page.getByRole('button', { name: '切换夜间模式' }).click()
    await page.getByRole('tab', { name: /^待补充/ }).click()
    await second.scrollIntoViewIfNeeded()
    assert.notEqual(await page.locator('.quote-chat-layout').evaluate(element => getComputedStyle(element).backgroundColor),
      'rgb(255, 255, 255)', 'Dark workspace must not retain the light background')
    await snapshot('supplement-dark')
    assert.deepEqual(errors, [])
    console.log('PASS: real grouped project forms, three-column desktop / single-column mobile, concise price blockers, folded terms, desktop/tablet/mobile/narrow and dark mode; GET only.')
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
