"""Export the configured PostgreSQL database schema and rows to a SQL file."""

from __future__ import annotations

import argparse
import datetime
import json
from pathlib import Path

from sqlalchemy import MetaData, create_engine, inspect
from sqlalchemy.dialects.postgresql import dialect as postgres_dialect


def sql_literal(value, column):
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, (dict, list)):
        encoded = json.dumps(value, ensure_ascii=False).replace("'", "''")
        return f"'{encoded}'::{column.type}"
    if isinstance(value, (datetime.date, datetime.datetime, datetime.time)):
        value = value.isoformat()
    return "'" + str(value).replace("'", "''") + "'"


def export_database(database_url: str, output: Path) -> None:
    engine = create_engine(database_url)
    metadata = MetaData()
    metadata.reflect(bind=engine)
    inspector = inspect(engine)
    dialect = postgres_dialect()
    lines = [
        "-- Firefly pricing database export.",
        "-- Generated by scripts/export_database_sql.py.",
        "BEGIN;",
        "SET client_encoding = 'UTF8';",
        "SET session_replication_role = replica;",
        "",
    ]

    table_names = inspector.get_table_names()
    for table_name in reversed(table_names):
        lines.append(f'DROP TABLE IF EXISTS "{table_name}" CASCADE;')
    lines.append("")
    # Render CREATE TABLE statements without modifying the source database.
    from sqlalchemy.schema import CreateTable

    for table in metadata.sorted_tables:
        lines.append(str(CreateTable(table).compile(dialect=dialect)) + ";")
    lines.append("")

    with engine.connect() as connection:
        for table in metadata.sorted_tables:
            rows = connection.execute(table.select()).mappings()
            for row in rows:
                columns = ", ".join(f'"{column.name}"' for column in table.columns)
                values = ", ".join(
                    sql_literal(row[column.name], column) for column in table.columns
                )
                lines.append(f'INSERT INTO "{table.name}" ({columns}) VALUES ({values});')
            if table.primary_key.columns:
                pk = next(iter(table.primary_key.columns))
                if pk.autoincrement:
                    sequence = f'"{table.name}_{pk.name}_seq"'
                    lines.append(
                        f"SELECT setval('{sequence}', "
                        f"COALESCE((SELECT MAX(\"{pk.name}\") FROM \"{table.name}\"), 1), "
                        f"EXISTS (SELECT 1 FROM \"{table.name}\"));"
                    )
    lines.extend(["", "SET session_replication_role = DEFAULT;", "COMMIT;", ""])
    output.write_text("\n".join(lines), encoding="utf-8")
    engine.dispose()


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--database-url", required=True)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "firefly_pricing_export.sql",
    )
    args = parser.parse_args()
    export_database(args.database_url, args.output)
    print(f"Exported database to {args.output}")


if __name__ == "__main__":
    main()
